import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"

// Newer emoji versions render as empty boxes on many current devices; raise this as OS support catches up.
const MAX_EMOJI_VERSION = "15.1"

const require = createRequire(import.meta.url)
const groups = JSON.parse(readFileSync(require.resolve("unicode-emoji-json/data-by-group.json"), "utf8"))
const datasetVersion = JSON.parse(readFileSync(require.resolve("unicode-emoji-json/package.json"), "utf8")).version

const versionNumber = (version) => Number.parseFloat(version)
const maxVersion = versionNumber(MAX_EMOJI_VERSION)

let total = 0
const lines = []
for (const group of groups) {
  const entries = group.emojis.filter((entry) => versionNumber(entry.emoji_version) <= maxVersion)
  if (!entries.length) continue
  total += entries.length
  lines.push(`  ${JSON.stringify(group.name)}: [`)
  for (const entry of entries) lines.push(`    [${JSON.stringify(entry.emoji)}, ${JSON.stringify(entry.name)}],`)
  lines.push("  ],")
}

const output = `// Generated by scripts/generate-unicode-emojis.mjs from unicode-emoji-json@${datasetVersion}. Do not edit by hand.
export const UNICODE_EMOJI_MAX_VERSION = ${JSON.stringify(MAX_EMOJI_VERSION)}

export const UNICODE_EMOJI_GROUPS: Record<string, ReadonlyArray<readonly [emoji: string, name: string]>> = {
${lines.join("\n")}
}
`

writeFileSync("lib/unicode-emojis.ts", output)
console.log(`Wrote ${total} emojis (emoji version <= ${MAX_EMOJI_VERSION}) to lib/unicode-emojis.ts`)
